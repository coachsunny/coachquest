// 根據 ID 查詢關主
export function getBossById(id) {
  if (!id) return null;
  return BOSSES.find(b => b.id === id) || null;
}

// 根據道館分類查詢關主列表
export function getBossesByCategory(category) {
  if (!category) return BOSSES;
  return BOSSES.filter(b => b.category === category);
}
